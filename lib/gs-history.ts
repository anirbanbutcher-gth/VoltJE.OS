export type HistoryEra = 'Ancient' | 'Medieval' | 'Modern' | 'World'

export interface HistoryEventItem {
  id: string
  era: HistoryEra
  year: string
  title: string
  note: string
  polityId: string
  scarred?: boolean
}

type RawRow = [string, string, string, string, boolean?]

function buildEra(era: HistoryEra, prefix: string, rows: RawRow[]): HistoryEventItem[] {
  return rows.map(([year, title, note, polityId, scarred], idx) => ({
    id: `${prefix}-${idx + 1}`,
    era,
    year,
    title,
    note,
    polityId,
    scarred: Boolean(scarred),
  }))
}

